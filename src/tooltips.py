class TooltipToast(QWidget):
    """Всплывающее окно для длинных подсказок."""

    def __init__(self) -> None:
        super().__init__(None)
        self.setWindowFlags(
            Qt.WindowType.ToolTip
            | Qt.WindowType.FramelessWindowHint
            | Qt.WindowType.WindowStaysOnTopHint
        )
        self.setAttribute(Qt.WidgetAttribute.WA_ShowWithoutActivating)
        self.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)

        layout = QVBoxLayout(self)
        layout.setContentsMargins(10, 8, 10, 8)

        self.label = QLabel(self)
        self.label.setWordWrap(True)
        self.label.setMaximumWidth(420)
        self.label.setTextFormat(Qt.TextFormat.PlainText)
        self.label.setStyleSheet(
            "QLabel { color: #f0f0f0; background: transparent; }"
        )
        layout.addWidget(self.label)

        self.setStyleSheet(
            "TooltipToast {"
            "  background-color: #2b2b2b;"
            "  border: 1px solid #555;"
            "  border-radius: 6px;"
            "}"
        )


class TooltipManager(QObject):
    """
    Менеджер подсказок.

    ВАЖНО:
      • QWidget-ы (TooltipToast, QTimer) создаются ЛЕНИВО — при первом
        реальном показе подсказки, то есть уже после того, как в
        приложении создан QApplication.
      • Для длинных подсказок стандартный QToolTip ОТКЛЮЧАЕТСЯ
        (widget.setToolTip("")), иначе Qt показал бы свой тултип
        одновременно с нашим toast.
    """

    def __init__(self) -> None:
        super().__init__()
        self._toast: Optional[TooltipToast] = None
        self._hide_timer: Optional[QTimer] = None
        self._current_widget: Optional[QWidget] = None

    # ------------------------------------------------------------------
    # Ленивая инициализация QWidget-ов
    # ------------------------------------------------------------------
    def _ensure_widgets(self) -> bool:
        if self._toast is not None:
            return True
        if QApplication.instance() is None:
            return False
        self._toast = TooltipToast()
        self._hide_timer = QTimer(self)
        self._hide_timer.setSingleShot(True)
        self._hide_timer.setInterval(TOAST_HIDE_DELAY_MS)
        self._hide_timer.timeout.connect(self._toast.hide)
        log.debug("TooltipManager: QWidget-ы созданы лениво")
        return True

    def install(self, widget: QWidget, text: str) -> None:
        """Вешает подсказку на виджет.

        Короткий текст → стандартный QToolTip.
        Длинный текст  → собственный TooltipToast (QToolTip отключается).
        """
        if not text:
            return

        if len(text) >= TOAST_THRESHOLD:
            widget.setToolTip("")
            widget.installEventFilter(self)
            widget.setProperty("_tooltip_text", text)
        else:
            widget.setToolTip(text)

    def eventFilter(self, obj: QObject, event: QEvent) -> bool:
        if event.type() == QEvent.Type.Enter:
            text = obj.property("_tooltip_text")
            if text:
                self._show_toast(obj, str(text))
        elif event.type() == QEvent.Type.Leave:
            if obj is self._current_widget:
                if self._hide_timer is not None:
                    self._hide_timer.start()
        return super().eventFilter(obj, event)

    def _show_toast(self, widget: QWidget, text: str) -> None:
        if not self._ensure_widgets():
            return
        assert self._toast is not None
        assert self._hide_timer is not None

        self._hide_timer.stop()
        self._current_widget = widget
        self._toast.label.setText(text)
        self._toast.adjustSize()

        # Позиционируем относительно виджета-иконки:
        # справа-сверху, чтобы не закрывать сам значок и поле.
        try:
            global_pos = widget.mapToGlobal(widget.rect().topRight())
        except Exception:
            global_pos = QCursor.pos()

        x = global_pos.x() + 12
        y = global_pos.y()

        screen = widget.screen() or widget.window().screen()
        if screen is not None:
            geo = screen.availableGeometry()
            if x + self._toast.width() > geo.right():
                # Не влезло справа — показываем слева от иконки
                try:
                    left_pos = widget.mapToGlobal(widget.rect().topLeft())
                    x = left_pos.x() - self._toast.width() - 12
                except Exception:
                    x = geo.right() - self._toast.width() - 8
            if y + self._toast.height() > geo.bottom():
                y = geo.bottom() - self._toast.height() - 8
            x = max(geo.left() + 8, x)
            y = max(geo.top() + 8, y)

        self._toast.move(x, y)
        log.debug("Показ toast-подсказки: %d символов", len(text))
        self._toast.show()


# Глобальный экземпляр. Создаётся при импорте, но НЕ создаёт QWidget —
# toast и таймер появятся только при первом показе подсказки.
_manager = TooltipManager()


def attach_tooltip(widget: QWidget, key: str) -> None:
    """
    Вешает подсказку на сам виджет по ключу из TOOLTIPS.

    Если текст короче TOAST_THRESHOLD — будет стандартный QToolTip.
    Если длиннее — всплывающий toast рядом с виджетом.
    """
    text = TOOLTIPS.get(key)
    if not text:
        log.warning("Нет текста подсказки для ключа: %s", key)
        return
    _manager.install(widget, text)


def attach_tooltip_text(widget: QWidget, text: str) -> None:
    """Вешает произвольную подсказку (не из словаря)."""
    _manager.install(widget, text)


