class InfoIcon(QLabel):
    """
    Маленькая иконка ⓘ, при наведении на которую показывается подсказка.

    Небольшой размер (16x16), серый цвет, курсор-«что это?».
    """

    def __init__(self, tooltip_text: str, parent: Optional[QWidget] = None) -> None:
        super().__init__("ⓘ", parent)
        self.setFixedSize(16, 16)
        self.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.setCursor(Qt.CursorShape.WhatsThisCursor)
        self.setStyleSheet(
            "QLabel {"
            "  color: #888;"
            "  font-size: 13px;"
            "  font-weight: bold;"
            "  border-radius: 8px;"
            "}"
            "QLabel:hover { color: #4a90d9; background-color: #eaf2fb; }"
        )
        # Вешаем подсказку на иконку, а не на поле
        _manager.install(self, tooltip_text)


def make_info_icon(key: str) -> Optional[InfoIcon]:
    """
    Создаёт иконку ⓘ с подсказкой по ключу из TOOLTIPS.

    Возвращает None, если ключ неизвестен (с записью warning в лог).
    Иконку нужно добавить в layout рядом с полем.
    """
    text = TOOLTIPS.get(key)
    if not text:
        log.warning("Нет текста подсказки для ключа: %s", key)
        return None
    return InfoIcon(text)


def make_info_icon_text(text: str) -> InfoIcon:
    """Создаёт иконку ⓘ с произвольным текстом подсказки."""
    return InfoIcon(text)


def with_info(
    field: QWidget,
    key: str,
    stretch: bool = True,
    spacing: int = 6,
) -> QWidget:
    """
    Оборачивает поле в QWidget-контейнер с иконкой ⓘ справа.

    Использование:
        form.addRow("URL сервера:", with_info(self.tr_url_input, "tr_url"))

    Это удобно в QFormLayout: в качестве правой колонки передаётся
    готовый контейнер, а не одиночный виджет.
    """
    container = QWidget()
    h = QHBoxLayout(container)
    h.setContentsMargins(0, 0, 0, 0)
    h.setSpacing(spacing)

    if stretch:
        h.addWidget(field, 1)
    else:
        h.addWidget(field)

    icon = make_info_icon(key)
    if icon is not None:
        h.addWidget(icon, 0, Qt.AlignmentFlag.AlignVCenter)

    return container


def with_info_widget(
    field: QWidget,
    tooltip_text: str,
    stretch: bool = True,
    spacing: int = 6,
) -> QWidget:
    """То же, что with_info, но подсказка задана текстом, а не ключом."""
    container = QWidget()
    h = QHBoxLayout(container)
    h.setContentsMargins(0, 0, 0, 0)
    h.setSpacing(spacing)

    if stretch:
        h.addWidget(field, 1)
    else:
        h.addWidget(field)

    icon = make_info_icon_text(tooltip_text)
    h.addWidget(icon, 0, Qt.AlignmentFlag.AlignVCenter)

    return container