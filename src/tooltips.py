def attach_tooltip(widget: QWidget, key: str) -> None:
    text = TOOLTIPS.get(key)
    if not text:
        log.warning("Нет текста подсказки для ключа: %s", key)
        return
    _manager.install(widget, text)


def attach_tooltip_text(widget: QWidget, text: str) -> None:
    _manager.install(widget, text)


